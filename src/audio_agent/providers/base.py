"""Abstract base interfaces for Audio Agent capability providers."""

from abc import ABC, abstractmethod
from pathlib import Path
from typing import Any, Dict, Iterator, List, Optional, Tuple

from audio_agent.schemas import (
    AcousticFeatures,
    Provenance,
    SoundEvent,
    SpeakerSegment,
    SpeechRegion,
    Word,
)


class BaseProvider(ABC):
    """Base class for all capability providers."""

    capability: str
    provider_name: str
    execution_mode: str = "local" # "local" or "cloud"

    @abstractmethod
    def is_available(self) -> bool:
        """Checks if provider dependencies and model weights are available."""
        pass

    def get_provenance(self, latency_seconds: Optional[float] = None) -> Provenance:
        """Returns standard provenance metadata for this provider run."""
        return Provenance(
            stage=self.capability,
            provider_name=self.provider_name,
            model_name=getattr(self, "model_name", "default"),
            execution_mode=self.execution_mode,
            latency_seconds=latency_seconds,
        )


class ASRProvider(BaseProvider):
    """Interface for Automatic Speech Recognition (ASR)."""
    capability: str = "asr"

    @abstractmethod
    def transcribe(self, audio_path: Path, language: Optional[str] = "en") -> Tuple[str, List[Word]]:
        """Transcribes audio and returns full transcript string plus timestamped words."""
        pass


class VADProvider(BaseProvider):
    """Interface for Voice Activity Detection."""
    capability: str = "vad"

    @abstractmethod
    def detect_speech_regions(self, audio_path: Path) -> List[SpeechRegion]:
        """Detects speech regions with start and end timestamps."""
        pass


class DiarizationProvider(BaseProvider):
    """Interface for Speaker Diarization."""
    capability: str = "diarization"

    @abstractmethod
    def diarize(self, audio_path: Path, num_speakers: Optional[int] = None) -> List[SpeakerSegment]:
        """Performs speaker diarization returning speaker intervals."""
        pass


class SoundEventProvider(BaseProvider):
    """Interface for Sound Event Detection."""
    capability: str = "sound_events"

    @abstractmethod
    def detect_events(self, audio_path: Path) -> List[SoundEvent]:
        """Detects acoustic and environmental sound events."""
        pass


class AcousticProvider(BaseProvider):
    """Interface for Acoustic Feature Extraction."""
    capability: str = "acoustic"

    @abstractmethod
    def extract_features(self, audio_path: Path) -> AcousticFeatures:
        """Extracts pitch, intensity, speech rate, and voice quality metrics."""
        pass


class LLMProvider(BaseProvider):
    """Interface for Local LLM Reasoning."""
    capability: str = "llm"

    @abstractmethod
    def generate(self, prompt: str, system_prompt: Optional[str] = None) -> str:
        """Generates response based on provided prompt and system instructions."""
        pass

    @abstractmethod
    def generate_stream(self, prompt: str, system_prompt: Optional[str] = None) -> Iterator[str]:
        """Yields streaming response tokens as they are generated by the LLM."""
        pass


class TTSProvider(BaseProvider):
    """Interface for Text-to-Speech (TTS) synthesis and streaming speech."""
    capability: str = "tts"
    sample_rate: int = 24000

    @abstractmethod
    def synthesize(self, text: str, output_path: Optional[Path] = None) -> Any:
        """Synthesizes complete text string to audio samples (numpy float32 array)."""
        pass

    @abstractmethod
    def stream_synthesize(self, text_stream: Iterator[str]) -> Iterator[Tuple[Any, int]]:
        """Consumes incoming text tokens/clauses and yields (audio_chunk_samples, sample_rate)."""
        pass


